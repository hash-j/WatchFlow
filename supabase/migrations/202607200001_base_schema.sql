begin;

-- Reconstructed WatchFlow baseline for FROM-ZERO environments. This file
-- intentionally contains only objects required before the Phase 3 migration.
-- It must not be applied blindly to an existing project that already has these
-- objects; reconcile migration provenance through the normal deployment tool.

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  timezone text not null default 'UTC',
  subscription_plan text not null default 'free',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.movies (
  id bigint generated by default as identity primary key,
  tmdb_id integer not null unique,
  title text not null,
  original_title text,
  overview text,
  poster_path text,
  backdrop_path text,
  release_date date,
  release_year integer,
  runtime_minutes integer,
  genres jsonb not null,
  director text,
  main_cast jsonb not null,
  original_language text,
  production_countries jsonb not null,
  public_rating numeric,
  trailer_key text,
  metadata_updated_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint movies_runtime_minutes_positive
    check (runtime_minutes is null or runtime_minutes > 0),
  constraint movies_public_rating_range
    check (public_rating is null or public_rating between 0 and 10)
);

create table public.user_movies (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  movie_id bigint not null references public.movies(id) on delete cascade,
  status text not null default 'want_to_watch',
  personal_rating numeric,
  review text,
  priority smallint not null default 0,
  queue_position integer,
  scheduled_for timestamptz,
  watched_at timestamptz,
  would_watch_again boolean,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint user_movies_user_movie_key unique (user_id, movie_id),
  constraint user_movies_status_check check (
    status in (
      'want_to_watch',
      'watch_next',
      'scheduled',
      'currently_watching',
      'watched',
      'on_hold',
      'dropped'
    )
  ),
  constraint user_movies_personal_rating_range
    check (personal_rating is null or personal_rating between 0 and 10),
  constraint user_movies_priority_range check (priority between 0 and 5)
);

alter table public.profiles enable row level security;
alter table public.movies enable row level security;
alter table public.user_movies enable row level security;

create policy watchflow_base_profiles_select_own
  on public.profiles
  for select
  to authenticated
  using ((select auth.uid()) = id);

create policy watchflow_base_profiles_update_own
  on public.profiles
  for update
  to authenticated
  using ((select auth.uid()) = id)
  with check ((select auth.uid()) = id);

create policy watchflow_base_movies_select_authenticated
  on public.movies
  for select
  to authenticated
  using (true);

create policy watchflow_base_user_movies_select_own
  on public.user_movies
  for select
  to authenticated
  using ((select auth.uid()) = user_id);

create policy watchflow_base_user_movies_insert_own
  on public.user_movies
  for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

create policy watchflow_base_user_movies_update_own
  on public.user_movies
  for update
  to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

create policy watchflow_base_user_movies_delete_own
  on public.user_movies
  for delete
  to authenticated
  using ((select auth.uid()) = user_id);

revoke all on table public.profiles from public, anon, authenticated;
revoke all on table public.movies from public, anon, authenticated;
revoke all on table public.user_movies from public, anon, authenticated;

grant select on table public.profiles to authenticated;
grant update (full_name, timezone, updated_at)
  on table public.profiles to authenticated;
grant select on table public.movies to authenticated;
grant select, insert, update, delete on table public.user_movies
  to authenticated;

grant all on table public.profiles, public.movies, public.user_movies
  to service_role;
grant usage, select on sequence public.movies_id_seq to service_role;

create or replace function public.watchflow_create_profile_for_auth_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, full_name)
  values (
    new.id,
    nullif(btrim(new.raw_user_meta_data ->> 'full_name'), '')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

revoke all on function public.watchflow_create_profile_for_auth_user()
  from public, anon, authenticated;

create trigger watchflow_auth_user_profile_created
after insert on auth.users
for each row execute function public.watchflow_create_profile_for_auth_user();

commit;
